#!/usr/bin/env node
/**
 * Team colors on the team hub (mak, 2026-11-05): the hub's house navy/blue
 * and gold become the team's own primary and secondary.
 *
 * Two steps, both idempotent, run as `node scripts/team-palette.mjs`:
 *
 * 1. Every navy/blue and gold color literal in public/team.css and
 *    public/player.css (player pages since 2026-11-05) is wrapped as
 *    `var(--tp-c-<hex>, <the literal>)` (rgba literals as `--tp-a-...`). With
 *    no `--tp-*` defined the fallback is the literal, so the stylesheet renders
 *    exactly as before on every page and every team.
 * 2. A generated block at the end of team.css (between the markers below)
 *    defines each `--tp-*` on a hub root that carries `data-team-palette`, as
 *    the team's primary (navy family) or secondary (gold family) mixed toward
 *    white or black by as much as the literal sits above or below its
 *    family's reference shade. So a near-black hero stays near-black, a pale
 *    surface stays pale, and both take the team's hue.
 *
 * Semantic colors (green up, red down, position colors) and neutral slate
 * greys fall outside both families and are left alone. Navy rgba below 0.3
 * alpha is shadow and stays neutral.
 *
 * Re-run after adding hub or player CSS with new navy/gold literals.
 */
import { readFileSync, writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";
import { dirname, join } from "node:path";

const PUBLIC = join(dirname(fileURLToPath(import.meta.url)), "..", "public");
/** Each stylesheet and the root its generated block keys on. */
const TARGETS = {
  team: { file: join(PUBLIC, "team.css"), root: ":is(.sct, #sct-table-armour)[data-team-palette]", owner: "team-render.ts" },
  player: { file: join(PUBLIC, "player.css"), root: ".scp[data-team-palette]", owner: "player-render.ts" },
};
const START = "/* ==== team palette (generated by scripts/team-palette.mjs; do not edit) ==== */";
const END = "/* ==== end team palette ==== */";

const REF = { navy: "#0b2345", gold: "#d4af37" };

function rgb(hex) {
  const h = hex.slice(1);
  const f = h.length === 3 ? h.split("").map((c) => c + c).join("") : h;
  return [0, 2, 4].map((i) => parseInt(f.slice(i, i + 2), 16));
}

function hsl([r, g, b]) {
  r /= 255; g /= 255; b /= 255;
  const max = Math.max(r, g, b), min = Math.min(r, g, b);
  const l = (max + min) / 2;
  if (max === min) return [0, 0, l];
  const d = max - min;
  const s = l > 0.5 ? d / (2 - max - min) : d / (max + min);
  let h;
  if (max === r) h = (g - b) / d + (g < b ? 6 : 0);
  else if (max === g) h = (b - r) / d + 2;
  else h = (r - g) / d + 4;
  return [h * 60, s, l];
}

/** "navy" | "gold" | null */
function family(c) {
  const [h, s, l] = hsl(c);
  if (h >= 40 && h <= 55 && s >= 0.45 && l > 0.08) return "gold";
  if (h >= 200 && h <= 235 && s >= 0.3) return "navy";
  return null;
}

/** The house hero's bright blue: navy literals between REF.navy and this run base -> bright. */
const BRIGHT_REF = "#176ab5";

/**
 * The team color shifted to the literal's lightness.
 *
 * gold family: the accent, mixed toward white or black by as much as the
 * literal sits above or below #d4af37.
 *
 * navy family, three bands (mak's Chiefs screenshot, 2026-11-05: mixing the
 * base toward white turned a red hero pink):
 *   darker than #0b2345   the base toward black;
 *   up to the hero blue   base -> --tp-bright (a team color white text reads
 *                          on, teamPalette()), so the hero is the team's own
 *                          vivid color rather than a pastel;
 *   lighter than that     --tp-bright toward white, at half the house tint
 *                          above 85% lightness, so pale surfaces stay pale
 *                          on red and orange teams.
 */
function mapped(c, fam) {
  const L = hsl(c)[2];
  if (fam === "gold") {
    const base = "var(--tp-accent)";
    const R = hsl(rgb(REF.gold))[2];
    if (Math.abs(L - R) < 0.02) return base;
    if (L > R) {
      const w = Math.round(((L - R) / (1 - R)) * 100);
      return w >= 100 ? "#fff" : `color-mix(in srgb, ${base} ${100 - w}%, #fff)`;
    }
    return `color-mix(in srgb, ${base} ${100 - Math.round(((R - L) / R) * 100)}%, #000)`;
  }
  const R = hsl(rgb(REF.navy))[2];
  const B = hsl(rgb(BRIGHT_REF))[2];
  if (Math.abs(L - R) < 0.02) return "var(--tp-primary)";
  if (L < R) return `color-mix(in srgb, var(--tp-primary) ${100 - Math.round(((R - L) / R) * 100)}%, #000)`;
  if (L <= B) {
    const t = Math.round(((L - R) / (B - R)) * 100);
    return t >= 100 ? "var(--tp-bright)" : `color-mix(in srgb, var(--tp-bright) ${t}%, var(--tp-primary))`;
  }
  let keep = (1 - (L - B) / (1 - B)) * 100;
  if (L > 0.85) keep /= 2;
  keep = Math.round(keep * 10) / 10;
  return keep <= 0 ? "#fff" : `color-mix(in srgb, var(--tp-bright) ${keep}%, #fff)`;
}

function run(name, { file: CSS, root, owner }) {
  let css = readFileSync(CSS, "utf8");
  const s = css.indexOf(START);
  if (s !== -1) css = css.slice(0, s).replace(/\s*$/, "\n");

  const defs = new Map();
  const wrapped = (src, i) => /var\(--tp-[\w-]+,\s*$/.test(src.slice(Math.max(0, i - 48), i));

  // Code only: comments are split out and left exactly as written.
  const parts = css.split(/(\/\*[\s\S]*?\*\/)/);
  const code = (fn) => parts.map((p, i) => (i % 2 ? p : fn(p))).forEach((p, i) => (parts[i] = p));

  code((seg) => seg.replace(/#[0-9a-fA-F]{6}\b|#[0-9a-fA-F]{3}\b/g, (lit, i, src) => {
    if (wrapped(src, i)) return lit;
    const fam = family(rgb(lit));
    if (!fam) return lit;
    const name = `--tp-c-${lit.slice(1).toLowerCase()}`;
    defs.set(name, mapped(rgb(lit), fam));
    return `var(${name}, ${lit})`;
  }));

  code((seg) => seg.replace(/rgba\(\s*(\d+),\s*(\d+),\s*(\d+),\s*([\d.]+)\s*\)/g, (lit, r, g, b, a, i, src) => {
    if (wrapped(src, i)) return lit;
    const c = [+r, +g, +b];
    const fam = family(c);
    if (!fam || (fam === "navy" && +a < 0.3)) return lit;
    const name = `--tp-a-${r}-${g}-${b}-${Math.round(+a * 1000)}`;
    const hex = "#" + c.map((x) => x.toString(16).padStart(2, "0")).join("");
    defs.set(name, `color-mix(in srgb, ${mapped(c, fam)} ${+(+a * 100).toFixed(1)}%, transparent)`);
    return `var(${name}, ${lit})`;
  }));
  css = parts.join("");

  // Text stays ink. A dark navy (under 30% lightness) set as a text `color`,
  // directly or through a token, reads var(--tp-ink): near-black with a trace of
  // the team, so a red base does not turn every heading and name maroon. The
  // same tokens still paint backgrounds in the team's color.
  {
    const plain = css.replace(/var\(--tp-[\w-]+, (#[0-9a-fA-F]+|rgba\([^)]*\))\)/g, "$1").replace(/\/\*[\s\S]*?\*\//g, "");
    const tok = new Map();
    for (const m of plain.matchAll(/(--[\w-]+)\s*:\s*([^;{}]+);/g)) if (!tok.has(m[1])) tok.set(m[1], m[2].trim());
    const resolve = (v, depth = 0) => {
      v = v.trim();
      if (/^#[0-9a-fA-F]{6}$/.test(v)) return v;
      const m = v.match(/^var\((--[\w-]+)\s*(?:,\s*(.+))?\)$/);
      if (!m || depth > 6) return null;
      return tok.has(m[1]) ? resolve(tok.get(m[1]), depth + 1) : m[2] ? resolve(m[2], depth + 1) : null;
    };
    const darkNavy = (v) => {
      const unwrapped = v.replace(/var\(--tp-[\w-]+, (#[0-9a-fA-F]+)\)/g, "$1");
      const hex = resolve(unwrapped);
      return !!hex && family(rgb(hex)) === "navy" && hsl(rgb(hex))[2] < 0.3;
    };
    let inked = 0;
    code((seg) => seg.replace(/(^|[;{\s])color(\s*:\s*)([^;{}!]+?)(\s*(?:!important)?\s*)(?=[;}])/g, (all, pre, colon, val, tail) => {
      if (val.startsWith("var(--tp-ink")) return all;
      if (!darkNavy(val)) return all;
      inked++;
      return `${pre}color${colon}var(--tp-ink, ${val})${tail}`;
    }));
    css = parts.join("");
    console.log(`${name}: ${inked} text colors newly set to ink`);
  }

  // Names already wrapped on an earlier run still need their definitions.
  for (const m of css.matchAll(/var\((--tp-c-([0-9a-f]{3,6})),/g)) {
    if (!defs.has(m[1])) defs.set(m[1], mapped(rgb(`#${m[2]}`), family(rgb(`#${m[2]}`))));
  }
  for (const m of css.matchAll(/var\((--tp-a-(\d+)-(\d+)-(\d+)-(\d+)),/g)) {
    if (defs.has(m[1])) continue;
    const c = [+m[2], +m[3], +m[4]];
    defs.set(m[1], `color-mix(in srgb, ${mapped(c, family(c))} ${+(+m[5] / 10).toFixed(1)}%, transparent)`);
  }

  const body = [...defs].sort(([a], [b]) => a.localeCompare(b)).map(([k, v]) => `  ${k}: ${v};`).join("\n");
  css +=
    `\n${START}\n` +
    `/* The root (${owner}) carries data-team-palette, --team-base,\n` +
    `   --team-accent and --team-bright (team/palette.ts) for a team that is\n` +
    `   not opted out (TEAM_PALETTE_OPT_OUT). */\n` +
    `${root} {\n` +
    `  --tp-primary: var(--team-base, var(--team-primary));\n` +
    `  --tp-accent: var(--team-accent, var(--team-secondary));\n` +
    `  --tp-bright: var(--team-bright, var(--tp-primary));\n` +
    `  --tp-ink: color-mix(in srgb, var(--tp-primary) 12%, #101827);\n` +
    `${body}\n}\n${END}\n`;
  writeFileSync(CSS, css);
  console.log(`${name}: ${defs.size} colors mapped`);
}

// `node scripts/team-palette.mjs [team|player]`; both by default.
const which = process.argv[2] ?? "all";
for (const [name, t] of Object.entries(TARGETS)) if (which === "all" || which === name) run(name, t);
