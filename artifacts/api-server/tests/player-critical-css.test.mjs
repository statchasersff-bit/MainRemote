/**
 * The player header's inline critical CSS (2026-11-27,
 * docs/MOBILE-PERF-PLAYER-2026-11-27.md).
 *
 * public/player-critical.css is generated from player.css by
 * scripts/player/critical-css.mjs. If player.css or the header markup changes
 * and the file is not regenerated, the inline copy would lay the header out
 * from old rules and, once player.css lands, re-apply them after it: these
 * tests fail first.
 */
import test, { after, before, describe } from "node:test";
import assert from "node:assert/strict";
import { readFile } from "node:fs/promises";
import { JSDOM } from "jsdom";
import { startServer } from "./helpers/server.mjs";
import {
  CRITICAL_PATH,
  builtPlayerCss,
  fetchFragments,
  parseCss,
  SHEET_GATE,
  selectCritical,
  splitSelectors,
} from "../scripts/player/critical-css.mjs";

const HEADER = "/* Generated by scripts/player/critical-css.mjs from player.css - do not edit. */\n";
let server;
let committed;
let built;

before(async () => {
  server = await startServer();
  committed = await readFile(CRITICAL_PATH, "utf8");
  built = await builtPlayerCss();
});
after(async () => server?.stop());

describe("player critical CSS", () => {
  test("the committed file is exactly what the generator writes for today's player.css and header", { timeout: 300_000 }, async () => {
    const { css } = selectCritical(built, await fetchFragments(server.origin), JSDOM);
    assert.ok(committed.startsWith(HEADER), "generated-file banner");
    assert.equal(
      committed.slice(HEADER.length),
      css,
      "public/player-critical.css is stale: run node scripts/player/critical-css.mjs",
    );
  });

  test("every inline rule is a player.css rule, in player.css order (values never hand-copied)", () => {
    const strip = (sel) => sel.replace(/:where\(\[data-scp-root\],[^)]*\)/g, "");
    const source = parseCss(built).filter((r) => r.type === "rule");
    const index = new Map();
    source.forEach((r, n) => {
      for (const sel of splitSelectors(r.sel)) {
        const key = `${r.ctx.join("|")}::${sel}`;
        if (!index.has(key)) index.set(key, []);
        index.get(key).push({ n, decls: r.body });
      }
    });
    const body = committed.slice(HEADER.length);
    assert.ok(body.endsWith(SHEET_GATE), "the panel gate closes the block");
    let last = -1;
    for (const r of parseCss(body.slice(0, -SHEET_GATE.length))) {
      for (const sel of splitSelectors(r.sel)) {
        const hits = index.get(`${r.ctx.join("|")}::${strip(sel)}`) ?? [];
        // Custom properties the header does not use are pruned, so compare
        // the other declarations, which must all be there verbatim.
        const want = r.body.split(";").filter((d) => d && !/^\s*--/.test(d));
        const hit = hits.find((h) => h.n >= last && want.every((d) => h.decls.includes(d)));
        assert.ok(hit, `inline rule not found in player.css after rule ${last}: ${r.ctx.join(" ")} ${sel.slice(0, 120)}`);
        last = hit.n;
      }
    }
  });

  test("player.css opens the panel gate, and nothing else in it sets those properties", async () => {
    const source = await readFile(new URL("../public/player.css", import.meta.url), "utf8");
    assert.match(source, /\.scp\[data-scp-root\] \{\s*--scp-sheet-vis: visible;\s*--scp-sheet-ovx: visible;\s*--scp-sheet-min: 0px;\s*\}/);
    assert.equal(committed.includes("--scp-sheet-vis:"), false, "the inline block never sets the gate open");
  });

  test("the header's container queries are in it (WP Rocket's critical CSS drops them)", () => {
    assert.match(committed, /container-name:pp/);
    assert.match(committed, /@container pp \(max-width: 560px\)\{[^@]*\.scp-phead-hero/);
    assert.ok(Buffer.byteLength(committed) < 60_000, `inline block stays small: ${Buffer.byteLength(committed)} bytes`);
  });

  test("the embedded fragment prints it once, ahead of the host fixes and the root; the app's own page does not", async () => {
    const res = await fetch(`${server.origin}/embed/player/jahmyr-gibbs?h1=1`);
    const html = await res.text();
    const style = `<style id="scp-critical">${committed.slice(HEADER.length).trim()}</style>`;
    assert.equal(html.split('<style id="scp-critical">').length - 1, 1);
    assert.ok(html.startsWith(style), "critical style first");
    assert.ok(html.indexOf('<style id="scp-host-header">') > html.indexOf("</style>"), "host fixes after it");
    assert.ok(html.indexOf('<div class="scp is-embed" data-scp-root') > html.indexOf('<style id="scp-host-header">'), "root after both styles");
    const tab = await (await fetch(`${server.origin}/embed/player/jahmyr-gibbs?h1=1&section=stats`)).text();
    assert.ok(tab.startsWith(style), "a tab address carries it too");
    const page = await (await fetch(`${server.origin}/player/jahmyr-gibbs`)).text();
    assert.equal(page.includes('id="scp-critical"'), false, "standalone page loads player.css render-blocking");
  });
});
